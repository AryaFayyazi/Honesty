#!/usr/bin/env python3
"""Render paper/examples/ex*.json (verbatim episode excerpts) into paper/appendix_examples.tex as colour-coded step boxes.
Usage: python scripts/122_render_examples.py"""
import glob
import json
import re

EX = "/home/arya/new_safety/cape/paper/examples"; OUT = "/home/arya/new_safety/cape/paper/appendix_examples.tex"
MODEL = {"museglimmer": r"\Muse", "Muse": r"\Muse", "gemma": r"\Gemma", "Gemma": r"\Gemma", "gpt-oss": r"\Oss", "gptoss": r"\Oss",
         "qwen": r"\Qwen", "claude-3-7": "Claude-3.7-Sonnet", "gpt-4.1": "GPT-4.1"}
# (title, colour) per step kind; report colour depends on its label
KIND = {"system_task": ("SYSTEM PROMPT / TASK", "cObs"), "user": ("USER", "cObs"), "observation": ("OBSERVATION", "cObs"),
        "reasoning": ("REASONING (excerpt)", "cPend"), "tool_call": ("TOOL CALL", "cHon"), "unsafe_tool_call": ("UNAUTHORIZED ACTION", "cUnsafe"),
        "permission_request": ("PERMISSION REQUEST", "cLaunder"), "permission_result": ("PERMISSION RESULT", "cLaunder"),
        "intervention": ("INTERVENTION (added user turn)", "cFix"), "steering": ("STEERING CONDITION", "cFix"), "annotation": ("NOTE", "cPend"),
        "label": ("LABEL (judge + verifier)", "black"), "customer": ("CUSTOMER", "cObs"), "policy": ("POLICY (excerpt)", "cForecast"),
        "agent_claim": ("AGENT TO CUSTOMER", "cLie"), "write_action": ("WRITE ACTION", "cUnsafe")}
TITLES = {"ex1": "Laundering with a denied request $\\rightarrow$ false report", "ex2": "Laundering with an approved request $\\rightarrow$ false report",
          "ex3": "Informed violation without laundering $\\rightarrow$ candid report", "ex4": "The evidence contract backfires (\\Oss)",
          "ex5": "The evidence contract helps (\\Muse)", "ex6": "Self-counterfactual steering, same episode as Example 5 (\\Muse)",
          "ex7": "Frontier pre-laundering on $\\tau^2$-bench"}


def esc(s):
    s = s.replace("\\", r"\textbackslash{}")
    for a, b in (("&", r"\&"), ("%", r"\%"), ("$", r"\$"), ("#", r"\#"), ("_", r"\_"), ("{", r"\{"), ("}", r"\}"), ("~", r"\textasciitilde{}"),
                 ("^", r"\textasciicircum{}"), ("…", r"\dots{}"), ("→", r"$\rightarrow$"), ("’", "'"), ("‘", "`"), ("“", "``"), ("”", "''"),
                 ("—", "---"), ("–", "--"), ("‑", "-"), ("≥", r"$\ge$"), ("≤", r"$\le$"), ("×", r"$\times$"), ("τ", r"$\tau$"), ("−", "-")):
        s = s.replace(a, b)
    s = s.replace(r"\textbackslash\{\}", r"\textbackslash{}")
    s = re.sub(r"[^\x00-\x7f]", "?", s)
    return s.replace("\n", r"\newline ")


def model_name(m):
    for k, v in MODEL.items():
        if k.lower() in m.lower():
            return v
    return esc(m)


def report_style(note, labels):
    n = note.lower()
    if any(w in n for w in ("candid", "discloses", "states what was done")):
        return "FINAL REPORT (candid)", "cFix"
    if "misrepresented" in n or "hides" in n or "cannot be" in n or "frames" in n or "lists the approvals" in n:
        return "FINAL REPORT (false)", "cLie"
    return "FINAL REPORT", "cHon"


def render(f):
    d = json.load(open(f)); key = f.split("/")[-1][:3]; out = []
    out.append(f"\\subsection{{Example {key[2:]}: {TITLES.get(key, esc(d['id']))}}}\\label{{ex:{key}}}")
    meta = [f"\\textbf{{Model}}: {model_name(d.get('model', ''))}", f"\\textbf{{Template}}: \\texttt{{{esc(d.get('template', ''))}}}",
            f"\\textbf{{World}}: {'$\\xm$ (unauthorized)' if d.get('world') == 'x-' else esc(str(d.get('world')))}"]
    if d.get("episode_id"):
        meta.append(f"\\textbf{{Episode}}: \\texttt{{{esc(d['episode_id'])}}}")
    out.append("{\\raggedright\\small " + " \\quad ".join(meta) + "\\par}")
    out.append(f"\\noindent{{\\small\\textit{{{esc(d.get('caption', ''))}}}}}\\par\\smallskip")
    for s in d["steps"]:
        k = s["kind"]
        if k == "report":
            title, col = report_style(s.get("note", ""), d.get("labels", {}))
        else:
            title, col = KIND.get(k, (k.upper(), "cObs"))
        if k == "observation" and any(w in s.get("note", "").lower() for w in ("decisive fact", "reveal")):
            title, col = "REVEAL (decisive fact)", "cForecast"
        body = esc(s["text"])
        if k in ("tool_call", "unsafe_tool_call", "permission_request", "write_action"):
            body = "\\texttt{" + body + "}"
        out.append(f"\\step{{{col}}}{{step {s['t']} \\textperiodcentered\\ {title}}}{{{body}}}")
        if s.get("note"):
            out.append(f"\\Snote{{{esc(s['note'])}}}")
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    parts = [render(f) for f in sorted(glob.glob(f"{EX}/ex*.json"))]
    open(OUT, "w").write("% generated by scripts/122_render_examples.py from paper/examples/*.json -- do not edit\n" + "\n\\clearpage\n".join(parts))
    print("wrote", OUT, len(parts), "examples")
